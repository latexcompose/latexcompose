"""Contains class `Cotainer`."""

from typing import TYPE_CHECKING, override

from .node import Node

if TYPE_CHECKING:
    from collections.abc import Iterable

    from latexcompose.base.context import IterTokensContext, IterTreeContext
    from latexcompose.tokens.token import Token


class Container(Node):
    """Base class for nodes that contain other nodes.

    A container manages a collection of child nodes and provides functionality
    for mounting, validating, and traversing those children.

    Additional children can be supplied dynamically by overriding
    :meth:`_compose_children`. These children are added during the mounting
    process.

    Attributes
    ----------
    _children : list[Node]
        Child nodes contained by this container. The list initially contains
        the children supplied to the constructor and is extended with
        dynamically composed children during mounting.
    _mounted : bool
        Indicates whether the container has already been mounted. Once
        mounted, the container does not repeat the mounting process.
    """

    def __init__(self, *children: Node) -> None:
        """Initialize the container with its initial child nodes.

        Parameters
        ----------
        *children : Node
            Initial child nodes to be stored in the container.
        """
        super().__init__()
        self._children: list[Node] = list(children)
        self._mounted = False

    def _compose_children(self) -> list[Node]:  # ruff: ignore[no-self-use]
        """Return additional child nodes to be added during mounting.

        Subclasses can override this method to dynamically provide additional
        children. The returned nodes are appended to the children supplied
        during initialization.

        The default implementation does not provide additional children.

        Returns
        -------
        list[Node]
            Additional child nodes to be added to the container.
        """
        return []

    def _mount(self) -> None:
        """Prepare the container and recursively mount its children.

        Mounting is performed only once. The method obtains additional
        children from :meth:`_compose_children`, appends them to the existing
        children, and recursively mounts the original child containers.

        If the container has already been mounted, the method returns
        immediately.

        Notes
        -----
        The method replaces the internal child collection with the combined
        collection and sets :attr:`_mounted` to ``True``.
        """
        if self._mounted:
            return

        composed_children = self._compose_children()
        children = [*self._children, *composed_children]

        for child in self._children:
            if isinstance(child, Container):
                child._mount()  # ruff: ignore[private-member-access]

        self._children = children
        self._mounted = True

    @override
    def validate(self) -> None:
        """Prepare the container and its children for validation.

        Mounting ensures that all dynamically composed children are included
        in the container before further processing.
        """
        self._mount()

    @override
    def iter_tree(
        self,
        parent: Node | None,
        context: IterTreeContext,
    ) -> Iterable[tuple[Node, Node | None]]:
        """Iterate over the container and its descendants.

        The container is mounted before traversal begins. The container itself
        is yielded first, followed by all descendants in depth-first order.

        Parameters
        ----------
        parent : Node or None
            Parent node of this container in the tree. Use ``None`` if the
            container is the root node.
        context : IterTreeContext
            Context used during tree traversal.

        Yields
        ------
        tuple[Node, Node or None]
            A tuple containing the current node and its parent node. The
            container is yielded first, followed by its descendants.

        Notes
        -----
        Each child is traversed recursively. The current container is supplied
        as the parent of its direct children.
        """
        self._mount()

        yield self, parent

        for child in self._children:
            yield from child.iter_tree(
                parent=self,
                context=context,
            )

    def iter_tokens(self, context: IterTokensContext) -> Iterable[Token]:
        """Yield all tokens generated by the child nodes.

        Before iteration begins, the container is mounted to ensure that all
        its children are available.

        Parameters
        ----------
        context : IterTokensContext
            Context used during token generation.

        Yields
        ------
        Token
            Tokens generated by the child nodes, in their original order.

        See Also
        --------
        _iter_children
            Iterates over the tokens generated by individual children.
        """
        self._mount()
        yield from self._iter_children(context)

    def _iter_children(
        self,
        context: IterTokensContext,
    ) -> Iterable[Token]:
        """Iterate over the tokens generated by all child nodes.

        Each child generates its tokens using the supplied context. Tokens
        are yielded in the same order as the children appear in the internal
        child collection.

        Parameters
        ----------
        context : IterTokensContext
            Context used during token generation.

        Yields
        ------
        Token
            Tokens generated by the child nodes.

        See Also
        --------
        iter_tokens
            Mounts the container before iterating over its children.

        Notes
        -----
        This method does not mount the container itself. Callers are
        responsible for ensuring that mounting has already taken place.
        """
        for child in self._children:
            yield from child.iter_tokens(context=context)
